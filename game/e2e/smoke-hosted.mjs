// Smoke test of a hosted build (no dev handle): login, menu, private room for two, duel starts.
import { chromium } from "playwright-core";
const URL = process.env.URL;
const b = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const res = [];
const check = (n, ok, i = "") => { res.push(ok); console.log("[smoke]", ok ? "PASS" : "FAIL", n, i); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function player() {
  const p = await (await b.newContext({ viewport: { width: 1366, height: 768 } })).newPage();
  p.errs = [];
  p.on("pageerror", (e) => p.errs.push(String(e)));
  await p.goto(URL);
  await p.getByText(/Play as guest|Играть как гость/).click({ timeout: 30000 });
  await p.getByRole("button", { name: /Кампания|Campaign/ }).first().waitFor({ timeout: 30000 });
  return p;
}
const h = await player();
check("hosted build loads and guest login works", true);
const duelBtn = h.getByRole("button", { name: /Дуэль 1×1|1v1 duel/ });
check("multiplayer available on the live title", await duelBtn.isEnabled());
await h.getByRole("button", { name: /^Кампания$|^Campaign$/ }).click();
check("campaign opens with the story", await h.getByRole("button", { name: /Пропустить|Skip/ }).isVisible());
await h.getByRole("button", { name: /Пропустить|Skip/ }).click();
await sleep(1500);
await h.waitForFunction(() => /метки|marker/i.test(document.querySelector(".nyc-hud")?.textContent ?? ""), null, { timeout: 8000 }).catch(() => {});
const hud = await h.locator(".nyc-root").innerText();
check("training ground starts (HUD visible)", /метки|marker/i.test(hud), JSON.stringify(hud.slice(0, 200)));
await h.keyboard.press("Escape");
await h.getByRole("button", { name: /В меню|^Menu$/ }).click();
const g = await player();
await duelBtn.click();
await h.getByRole("button", { name: /Может войти любой|Anyone can join/ }).click({ force: true });
await h.locator("button.idos-press", { hasText: /^Создать комнату$|^Create a room$/ }).last().click({ force: true });
const ib = h.getByText(/Приглашение:|Invite:/).first();
await ib.waitFor({ timeout: 20000 });
const inv = (await ib.innerText()).split(/:\s*/).slice(1).join(":").trim();
check("private room created on the live title", /^[0-9a-f]+:[A-Z0-9]+$/i.test(inv));
await g.getByRole("button", { name: /Войти в комнату по коду|Join a room by code/ }).click();
await g.getByRole("button", { name: /По приглашению|By invite/ }).click({ force: true });
await g.getByPlaceholder(/Приглашение|Invite/).fill(inv);
await g.getByRole("button", { name: /^Войти$|^Join$/ }).click({ force: true });
await g.getByRole("button", { name: /^Готов$|^Ready$/ }).waitFor({ timeout: 20000 });
await g.getByRole("button", { name: /^Готов$|^Ready$/ }).click({ force: true });
await sleep(1500);
await h.locator(".nyc-hud").waitFor({ timeout: 8000 }).catch(() => {});
await h.locator('[data-tutorial-anchor="multiplayer:play"]').click({ force: true });
await h.getByText(/^Комната$|^Room$/).first().waitFor({ timeout: 20000 });
await g.getByText(/^Комната$|^Room$/).first().waitFor({ timeout: 20000 });
check("both clients in the duel lobby", true);
await h.locator(".nyc-panel").getByRole("button", { name: /^Готов$|^Ready$/ }).click();
await g.locator(".nyc-panel").getByRole("button", { name: /^Готов$|^Ready$/ }).click();
const started = await g.getByText(/Старт через|Starting in/).waitFor({ timeout: 15000 }).then(() => true).catch(() => false);
check("match countdown on the guest (snapshots over WebRTC)", started);
await sleep(4000);
const score = await g.locator(".nyc-score").innerText().catch(() => "");
check("match running with score/timer", /\d\s*:\s*\d/.test(score), score.replace(/\n/g, " "));
await g.screenshot({ path: "e2e/out/hosted-guest-match.png" });
check("no page errors", h.errs.length + g.errs.length === 0, [...h.errs, ...g.errs].join(" | "));
await b.close();
console.log("[smoke]", `${res.filter(Boolean).length}/${res.length} passed`);
process.exit(res.every(Boolean) ? 0 : 1);
